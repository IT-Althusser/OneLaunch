    private static final Map<String, List<Clause>> CONTRACTS = build();

    private static Map<String, List<Clause>> build() {
        Map<String, List<Clause>> map = new LinkedHashMap<>();
        map.put("白底图", WHITE);
        map.put("场景图", SCENE);
        map.put("模特图", MODEL);
        map.put("对比图", COMPARE);
        map.put("尺寸图", DIMENSION);
        return Map.copyOf(map);
    }

    private ImageQualityContract() {}

    static List<Clause> clauses(String type) {
        List<Clause> clauses = CONTRACTS.get(type);
        if (clauses == null) throw new IllegalArgumentException("type 必须为白底图/场景图/模特图/对比图/尺寸图");
        return clauses;
    }

    /** 生成端验收块：逐条带 【id】 标记（编辑模型对起始指令最敏感，本块在提示词中的位置由调用方决定）。 */
    static String generationBlock(String type) {
        return clauses(type).stream().map(c -> "【" + c.id() + "】" + c.generation()).collect(Collectors.joining("\n"));
    }

    /** 质检端判据块：与生成端同一组 【id】（同一条款两端共用一个 id，漂移由单测拦截）。 */
    static String qaBlock(String type) {
        return clauses(type).stream().map(c -> "【" + c.id() + "】" + c.qa()).collect(Collectors.joining("\n"));
    }

    static Set<String> clauseIds(String type) {
        return clauses(type).stream().map(Clause::id).collect(Collectors.toSet());
    }

